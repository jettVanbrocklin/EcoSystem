import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.optimize import minimize, brentq
from IPython.display import display

r = 1.0
Q = np.diag([2.0, 1.0])

def loss(theta, b):
    delta = theta - np.array([2.0, b])
    return 0.5 * delta @ Q @ delta

def gradient(theta, b):
    return Q @ (theta - np.array([2.0, b]))

# ||theta||_1 <= r is equivalent to these four linear inequalities:
# theta1 + theta2 <= r, theta1 - theta2 <= r,
# -theta1 + theta2 <= r, -theta1 - theta2 <= r.
C = np.array([
    [ 1.,  1.],
    [ 1., -1.],
    [-1.,  1.],
    [-1., -1.]
])

def solve_l1(b):
    result = minimize(
        fun=lambda theta: loss(theta, b),
        x0=np.zeros(2),
        jac=lambda theta: gradient(theta, b),
        method="SLSQP",
        constraints={
            "type": "ineq",
            "fun": lambda theta: r - C @ theta,
            "jac": lambda theta: -C
        },
        options={"ftol": 1e-12, "maxiter": 1000}
    )
    if not result.success:
        raise RuntimeError(result.message)
    return result.x

def solve_l2(b):
    a = np.array([2.0, b])
    if np.linalg.norm(a) <= r:
        return a

    # KKT stationarity:
    # (Q + lambda*I) theta = Q*a, lambda >= 0.
    # Numerically find lambda giving ||theta||_2 = r.
    def theta_at(lam):
        return np.linalg.solve(Q + lam * np.eye(2), Q @ a)

    upper = 1.0
    while np.linalg.norm(theta_at(upper)) > r:
        upper *= 2

    lam = brentq(
        lambda value: np.linalg.norm(theta_at(value)) - r,
        0.0, upper, xtol=1e-14
    )
    return theta_at(lam)

