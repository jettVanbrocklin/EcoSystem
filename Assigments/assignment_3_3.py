for d in degrees:
    # Legendre basis spans exactly the same degree-d polynomial space
    # as [1, x, ..., x^d], but improves numerical conditioning.
    A = legvander(2 * x_train - 1, d)
    B = legvander(2 * x_held - 1, d)

    # Solve least squares using an SVD-based solver.
    # Avoid forming the ill-conditioned normal equations.
    coefficients = np.linalg.lstsq(A, y_train, rcond=None)[0]

    train_predictions = A @ coefficients
    held_predictions = B @ coefficients

    # L = ||prediction - y||^2 / (2n)
    train_losses[d] = 0.5 * np.mean(
        (train_predictions - y_train)**2, axis=0
    )
    held_losses[d] = 0.5 * np.mean(
        (held_predictions - y_held)**2, axis=0
    )

