# Question 4: your code here
import numpy as np
import matplotlib.pyplot as plt

# Assumed data; replace x and y with the textbook data if available.
rng = np.random.default_rng(42)
x = np.linspace(-1, 1, 15)
y = np.sin(np.pi * x) + rng.normal(0, 0.12, len(x))

# Preserve the monomial basis: changing basis changes the ridge penalty.
Phi = np.vander(x, N=15, increasing=True)

# Fourteen decades
lambdas = np.logspace(-12, 2, 1401)

def ridge_path(A, targets, penalties):
    """Objective: ||A theta-y||²/(2m) + lambda*||theta||²/2."""
    U, s, Vt = np.linalg.svd(A, full_matrices=False)
    z = U.T @ targets
    alpha = len(targets) * penalties
    coefficients = Vt.T @ (
        s[:, None] * z[:, None]
        / (s[:, None]**2 + alpha[None, :])
    )
    return coefficients

# Full-data L-curve, evaluated stably using the SVD.
U, s, Vt = np.linalg.svd(Phi, full_matrices=False)
z = U.T @ y
n = len(y)

condition_gram = (s[0] / s[-1])**2
print(f"Gram condition number from SVD: {condition_gram:.6e}")

alpha = n * lambdas[:, None]
d = s[None, :]**2

f = d / (d + alpha)
q = alpha / (d + alpha)

# Spectral contributions to residual squared and coefficient norm squared
R_terms = q**2 * z[None, :]**2
N_terms = d * z[None, :]**2 / (d + alpha)**2

R = R_terms.sum(axis=1)
N = N_terms.sum(axis=1)

# Derivatives with respect to t = log(lambda).
# Analytical derivatives avoid noisy finite-difference curvature.
R_prime = (2 * R_terms * f).sum(axis=1)
R_second = (R_terms * (4*f**2 - 2*f*q)).sum(axis=1)

N_prime = (-2 * N_terms * q).sum(axis=1)
N_second = (N_terms * (4*q**2 - 2*q*f)).sum(axis=1)

# Coordinates: log(R/(2n)), log(N)
dx = R_prime / R
dy = N_prime / N
ddx = R_second / R - dx**2
ddy = N_second / N - dy**2

curvature = (dx * ddy - dy * ddx) / (dx**2 + dy**2)**1.5

# Positive curvature selects the usual L corner as lambda increases:
# the descending vertical arm turns toward the horizontal arm.
elbow_index = np.argmax(curvature)
lambda_elbow = lambdas[elbow_index]

# Fixed validation split of the same 15 observations.
indices = rng.permutation(n)
train_indices = indices[:10]
validation_indices = indices[10:]

validation_coefficients = ridge_path(
    Phi[train_indices], y[train_indices], lambdas
)
validation_predictions = Phi[validation_indices] @ validation_coefficients
validation_loss = 0.5 * np.mean(
    (validation_predictions - y[validation_indices, None])**2,
    axis=0
)

validation_index = np.argmin(validation_loss)
lambda_validation = lambdas[validation_index]

print(f"Curvature-selected lambda:  {lambda_elbow:.8e}")
