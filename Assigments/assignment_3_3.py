# Question 12: your code here
import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import minimize, brentq
from scipy.special import expit

# Coordinates consistent with the figure and its reported thresholds.
x_fixed = np.r_[np.linspace(0.5, 2.0, 6),
                np.linspace(2.6, 4.1, 6)]
y_fixed = np.r_[np.zeros(6), np.ones(6)]

start = 4.4
logistic_lambda = 0.01

def dataset(t):
    return np.r_[x_fixed, t], np.r_[y_fixed, 1.0]

def least_squares(x, y):
    A = np.column_stack([np.ones(len(x)), x])
    return np.linalg.lstsq(A, y, rcond=None)[0]

def ls_threshold(t):
    x, y = dataset(t)
    intercept, slope = least_squares(x, y)
    return (0.5 - intercept) / slope

def logistic_fit(x, y):
    A = np.column_stack([np.ones(len(x)), x])

    # Mean cross-entropy + lambda*slope²/2.
    # The intercept is not penalized.
    def objective_and_gradient(theta):
        z = A @ theta
        loss = (
            np.mean(np.logaddexp(0, z) - y*z)
            + logistic_lambda * theta[1]**2 / 2
        )
        gradient = A.T @ (expit(z) - y) / len(y)
        gradient[1] += logistic_lambda * theta[1]
        return loss, gradient

    result = minimize(
        objective_and_gradient,
        x0=np.array([-7.8, 3.4]),
        jac=True,
        method="BFGS",
        options={"gtol": 1e-10, "maxiter": 1000}
    )
    # Some optimizers report precision loss despite a tiny gradient.
    if np.linalg.norm(result.jac, ord=np.inf) > 1e-7:
        raise RuntimeError(result.message)
    return result.x

# Clean fit and exact numerical crossing.
a_clean, b_clean = least_squares(x_fixed, y_fixed)
clean_threshold = (0.5 - a_clean) / b_clean

critical_t = brentq(
    lambda t: ls_threshold(t) - 2.6, start, 26
)

positions = np.linspace(start, 50, 401)
