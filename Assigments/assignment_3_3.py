from numpy.polynomial.legendre import legvander
from IPython.display import display

# Assumed data setup; the supplied pages do not specify these values.
SEED = 42
N_TRAIN = 15
N_HELD = 2001
N_DRAWS = 400
SIGMA = 0.12
degrees = np.arange(15)

def true_function(x):
    return np.sin(2 * np.pi * x)

rng = np.random.default_rng(SEED)
x_train = np.linspace(0, 1, N_TRAIN)
x_held = np.linspace(0, 1, N_HELD)
noise_floor = SIGMA**2 / 2

# Each column is an independent experiment.
# Held out labels have noise independent of the training labels.
y_train = (
    true_function(x_train)[:, None]
    + rng.normal(0, SIGMA, (N_TRAIN, N_DRAWS))
)
y_held = (
    true_function(x_held)[:, None]
    + rng.normal(0, SIGMA, (N_HELD, N_DRAWS))
)

