# ------------------------------------------------------------
# 2. Calculate all individual sample gradients at the probe
# ------------------------------------------------------------
# Sample loss:
# ell_i(theta) = 0.5 * (x_i.T @ theta - y_i)^2
#
# Sample gradient:
# grad ell_i(theta) = x_i * (x_i.T @ theta - y_i)

residuals = X @ theta - y
sample_gradients = X * residuals[:, None]

# Full gradient = average of all sample gradients.
full_gradient = sample_gradients.mean(axis=0)

# Each row is an individual gradient minus the full gradient.
