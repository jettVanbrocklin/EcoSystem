# 3. Estimate the expected SQUARED gradient deviation
# ------------------------------------------------------------
def estimate_variances(resamplings, rng):
    estimates = []

    for B in batch_sizes:
        # One independently sampled batch per row.
        # Sampling WITH replacement is essential for exact 1/B scaling.
        indices = rng.integers(
            0, n, size=(resamplings, B)
        )

        # Average centered gradients within each batch:
        # this equals g_B - full_gradient.
        errors = centered_gradients[indices].mean(axis=1)

        squared_errors = np.sum(errors**2, axis=1)
        estimates.append(squared_errors.mean())

    return np.array(estimates)


