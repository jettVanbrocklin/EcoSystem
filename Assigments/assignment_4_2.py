d = 10

# ------------------------------------------------------------
# 1. Repeatedly generate data and measure covariance conditioning
# ------------------------------------------------------------
def condition_numbers(n, repetitions=10_000, seed=42, batch_size=100):
    """
    Draw n observations from N(0, I_d) in each repetition.

    Estimate the mean and sample covariance, then calculate
        kappa = largest eigenvalue / smallest eigenvalue.

    Returns one condition number per repetition.
    """

    # Centering the observations gives rank(S) <= n - 1.
    # Therefore the covariance is mathematically singular if n <= d.
    if n <= d:
        return np.full(repetitions, np.inf)

    # Reproducible, separate random stream for each sample size.
    rng = np.random.default_rng(
        np.random.SeedSequence([seed, n])
    )

    kappas = np.empty(repetitions)

    # Use small batches to avoid storing every simulated dataset at once.
    for start in range(0, repetitions, batch_size):
        count = min(batch_size, repetitions - start)

        # Shape: (number of repetitions in batch, samples, dimensions)
        X = rng.standard_normal((count, n, d))

        # Subtract each dataset's estimated mean.
        X -= X.mean(axis=1, keepdims=True)

        # S = X_centered.T @ X_centered / (n - 1)
        # Compute one covariance matrix for each dataset in the batch.
        S = np.einsum(
            "bni,bnj->bij", X, X, optimize=True
        ) / (n - 1)

        # Eigenvalues are returned in ascending order.
        eigenvalues = np.linalg.eigvalsh(S)

        kappas[start:start + count] = (
            eigenvalues[:, -1] / eigenvalues[:, 0]
        )

    return kappas


