# Question 10: your code here
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from IPython.display import display

METHODS = ["SGD", "Momentum", "RMSProp", "Adam"]
RATES = np.logspace(-3, 1, 40)  # Four decades, 40 candidates.

STEPS = 1500
RUNS = 12
BATCH_SIZE = 16
EPSILON = 1e-8


# ------------------------------------------------------------
# 1. Generate either least-squares dataset
# ------------------------------------------------------------
def make_dataset(n, flat_scale, target, noise, seed):
    rng = np.random.default_rng(seed)

    X = rng.standard_normal((n, 2)) @ np.diag(
        [1.0, flat_scale]
    )
    y = X @ np.array(target) + noise * rng.standard_normal(n)

    return X, y


# ------------------------------------------------------------
# 2. Sweep all rates for all four optimizers
# ------------------------------------------------------------
def tune_optimizers(X, y, theta0, seed=42):
    n, d = X.shape

    H = X.T @ X / n
    theta_hat = np.linalg.lstsq(X, y, rcond=None)[0]

    number_of_rates = len(RATES)

    # Axes: method, candidate rate, independent run, coordinate.
    theta = np.broadcast_to(
        np.array(theta0, dtype=float),
        (4, number_of_rates, RUNS, d)
    ).copy()

    m = np.zeros_like(theta)
    v = np.zeros_like(theta)

    active = np.ones((4, number_of_rates), dtype=bool)
    history = np.empty((4, number_of_rates, STEPS + 1))

    def gaps(parameters):
        error = parameters - theta_hat
        return 0.5 * np.einsum(
            "mcri,ij,mcrj->mcr", error, H, error
        )

    history[:, :, 0] = gaps(theta).mean(axis=2)

    # Broadcasting shape: candidate rate, run, coordinate.
    learning_rates = RATES[:, None, None]
    rng = np.random.default_rng(seed)

    for j in range(1, STEPS + 1):
        # Runs are independent; methods and rates share batch draws.
        indices = rng.integers(
            n, size=(RUNS, BATCH_SIZE)
        )
        xb = X[indices]
        yb = y[indices]

        residuals = (
            np.einsum("mcrd,rbd->mcrb", theta, xb)
            - yb[None, None, :, :]
        )

        gradient = np.einsum(
            "mcrb,rbd->mcrd", residuals, xb
        ) / BATCH_SIZE

        # SGD
        theta[0] -= learning_rates * gradient[0]

        # Momentum: unnormalized velocity convention.
        m[1] = 0.9 * m[1] + gradient[1]
        theta[1] -= learning_rates * m[1]

        # RMSProp
        v[2] = 0.9 * v[2] + 0.1 * gradient[2]**2
        theta[2] -= learning_rates * gradient[2] / (
            np.sqrt(v[2]) + EPSILON
        )

        # Adam, including bias correction.
        m[3] = 0.9 * m[3] + 0.1 * gradient[3]
        v[3] = 0.999 * v[3] + 0.001 * gradient[3]**2

        m_hat = m[3] / (1 - 0.9**j)
        v_hat = v[3] / (1 - 0.999**j)

        theta[3] -= learning_rates * m_hat / (
            np.sqrt(v_hat) + EPSILON
        )

        mean_gap = gaps(theta).mean(axis=2)

        # Permanently exclude divergent candidate rates.
        active &= np.isfinite(mean_gap) & (mean_gap < 1e60)

        theta[~active] = 0
        m[~active] = 0
        v[~active] = 0

        history[:, :, j] = np.where(
            active, mean_gap, np.inf
        )

    # Select each method's rate independently.
    best_indices = np.argmin(history[:, :, -1], axis=1)

    selected_curves = history[
        np.arange(4), best_indices, :
    ]

    final_individual_gaps = gaps(theta)
    rows = []

    for method_index, method in enumerate(METHODS):
        rate_index = best_indices[method_index]
        individual = final_individual_gaps[
            method_index, rate_index
        ]

        rows.append({
            "Method": method,
            "Best alpha": RATES[rate_index],
            "Mean final gap": selected_curves[method_index, -1],
            "Final gap standard error": (
                individual.std(ddof=1) / np.sqrt(RUNS)
            )
        })

    return (
        pd.DataFrame(rows),
        selected_curves,
        np.linalg.cond(H)
    )


