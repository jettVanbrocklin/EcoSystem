# Question 12: your code here
import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
from IPython.display import display

# ------------------------------------------------------------
# 1. Targets, node counts, and random kink locations
# ------------------------------------------------------------
rng = np.random.default_rng(42)

N_values = 2 ** np.arange(1, 9)  # 2, 4, ..., 256
c_values = rng.uniform(0.0, 1.0, size=60)

def smooth_target(x):
    return np.sin(2 * np.pi * x)

# Dense evaluation grid for the smooth target's maximum error.
evaluation_grid = np.linspace(0.0, 1.0, 200_001)
smooth_truth = smooth_target(evaluation_grid)

smooth_errors = []
kink_errors = np.empty((len(N_values), len(c_values)))

# ------------------------------------------------------------
# 2. Build interpolants and measure maximum errors
# ------------------------------------------------------------
for i, N in enumerate(N_values):
    # N interior nodes + 2 endpoints.
    nodes = np.linspace(0.0, 1.0, N + 2)

    # Piecewise-linear interpolant of the smooth target.
    smooth_node_values = smooth_target(nodes)

    smooth_interpolated = np.interp(
        evaluation_grid, nodes, smooth_node_values
    )

    smooth_errors.append(
        np.max(np.abs(smooth_interpolated - smooth_truth))
    )

    # Piecewise-linear interpolants of |x-c|.
    for k, c in enumerate(c_values):
        kink_node_values = np.abs(nodes - c)

        # For this target, the maximum interpolation error
        # occurs exactly at x=c, where the true value is zero.
        interpolated_at_c = np.interp(
            c, nodes, kink_node_values
        )

        kink_errors[i, k] = abs(interpolated_at_c)

smooth_errors = np.array(smooth_errors)

# Average the MAXIMUM error of each kink interpolant.
mean_kink_errors = kink_errors.mean(axis=1)

# One fixed random c, retained across all node counts.
single_kink_errors = kink_errors[:, 0]

# ------------------------------------------------------------
