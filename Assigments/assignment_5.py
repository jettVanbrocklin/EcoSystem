# Question 12: your code here
import matplotlib.pyplot as plt
from time import perf_counter
from threadpoolctl import threadpool_limits

# ---------- Full model ----------
nx, nsteps, stride = 200, 1400, 20
c, nu, dt = 0.9, 0.004, 2e-4
dx = 1.0 / (nx - 1)
grid = np.linspace(0.0, 1.0, nx)

diffusion = nu * dt / dx**2
courant = c * dt / dx
peclet = c * dx / nu

print("Stability numbers:", diffusion, courant, peclet)
assert diffusion <= 0.5 and courant <= 1.0 and peclet <= 2.0

# Explicit 200 x 200 matrix, including the fixed boundary nodes.
A = np.zeros((nx, nx), dtype=np.float64)
i = np.arange(1, nx - 1)
A[i, i-1] = nu / dx**2 + c / (2*dx)
A[i, i]   = -2*nu / dx**2
A[i, i+1] = nu / dx**2 - c / (2*dx)

def initial_condition(width):
    u = np.exp(-((grid - 0.18) / width)**2)
    u[[0, -1]] = 0.0
    return u

def march(M, initial):
    """Forward Euler; save every twentieth step."""
    B = np.eye(len(initial)) + dt * M
    state = initial.copy()
    snapshots = np.empty((len(initial), nsteps // stride))
    j = 0

    for step in range(1, nsteps + 1):
        state = B @ state
        if step % stride == 0:
            snapshots[:, j] = state
            j += 1

    return snapshots

u0 = initial_condition(0.055)
u0_wide = initial_condition(0.11)

X = march(A, u0)
X_wide = march(A, u0_wide)

# Uncentered POD basis trained ONLY on the original pulse.
with threadpool_limits(limits=1):
    V, sigma, _ = np.linalg.svd(X, full_matrices=False)

def reduced_solution(r, initial):
    Vr = V[:, :r]
    Ar = Vr.T @ A @ Vr
    return Vr @ march(Ar, Vr.T @ initial)

def relative_error(reference, approximation):
    return (
        np.linalg.norm(reference - approximation, "fro")
        / np.linalg.norm(reference, "fro")
    )

# ---------- Errors against rank ----------
ranks = np.arange(1, 17)
errors = []
wide_errors = []
discarded_energy = []

for r in ranks:
    errors.append(relative_error(X, reduced_solution(r, u0)))
    wide_errors.append(
        relative_error(X_wide, reduced_solution(r, u0_wide))
    )
    discarded_energy.append(
        np.sum(sigma[r:]**2) / np.sum(sigma**2)
    )

errors = np.asarray(errors)
wide_errors = np.asarray(wide_errors)
discarded_energy = np.asarray(discarded_energy)

print("\n r    Original ROM error    Wider-pulse ROM error    POD error floor")
for r in (2, 4, 8):
    print(
        f"{r:2d}    {errors[r-1]:18.8f}    "
        f"{wide_errors[r-1]:21.8f}    "
        f"{np.sqrt(discarded_energy[r-1]):15.8f}"
    )

print("\nInitial-state projection errors for the wider pulse:")
for r in (2, 4, 8):
    Vr = V[:, :r]
    error = np.linalg.norm(u0_wide - Vr @ (Vr.T @ u0_wide))
    print(f"r={r}: {error / np.linalg.norm(u0_wide):.6f}")

# ---------- Online timing ----------
def median_time(function, repeats=7):
    function()  # Warm-up
    elapsed = []
    for _ in range(repeats):
        start = perf_counter()
        function()
        elapsed.append(perf_counter() - start)
    return np.median(elapsed)

# One BLAS thread gives a consistent comparison for these small matrices.
# Exclude POD and Ar construction; include reconstruction of ROM snapshots.
with threadpool_limits(limits=1):
    full_time = median_time(lambda: march(A, u0))

    print(f"\nFull dense solver: {1000*full_time:.3f} ms")
    for r in (2, 4, 8):
        Vr = V[:, :r]
        Ar = Vr.T @ A @ Vr
        a0 = Vr.T @ u0

        rom_time = median_time(lambda: Vr @ march(Ar, a0))
        print(
            f"r={r}: {1000*rom_time:.3f} ms, "
            f"speedup = {full_time / rom_time:.2f}x"
        )

# ---------- Plots ----------
fig, axes = plt.subplots(1, 3, figsize=(16, 4.5))

# Squared errors are directly comparable with discarded energy.
axes[0].semilogy(ranks, errors**2, "o-", label="Original ROM error²")
axes[0].semilogy(ranks, wide_errors**2, "s-", label="Wider-pulse ROM error²")
axes[0].semilogy(
    ranks, discarded_energy, "k--",
    label="Discarded training energy"
)
axes[0].set(
    xlabel="Rank r", ylabel="Squared relative error / energy fraction",
    title="Trajectory error versus rank"
)
axes[0].legend(fontsize=8)

