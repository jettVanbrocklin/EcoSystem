# Question 2: your code here
from jax.flatten_util import ravel_pytree

# Small example dataset: four samples, each with two input features.
X = jnp.array([
    [0.2, -0.4],
    [0.7,  0.3],
    [-0.5, 0.8],
    [1.0, -0.2]
], dtype=jnp.float64)

y = jnp.array([[0.1], [0.6], [-0.3], [0.8]], dtype=jnp.float64)

# Two layers: 2 inputs -> 3 hidden neurons -> 1 output.
rng = np.random.default_rng(0)
params = {
    "W1": jnp.array(rng.normal(0, 0.3, (2, 3)), dtype=jnp.float64),
    "b1": jnp.array(rng.normal(0, 0.1, (3,)), dtype=jnp.float64),
    "W2": jnp.array(rng.normal(0, 0.3, (3, 1)), dtype=jnp.float64),
    "b2": jnp.array(rng.normal(0, 0.1, (1,)), dtype=jnp.float64),
}

def network(params, X):
    hidden = jnp.tanh(X @ params["W1"] + params["b1"])
    return hidden @ params["W2"] + params["b2"]

def loss(params):
    return jnp.mean((network(params, X) - y)**2)

# Flatten the parameters so each coordinate can be checked.
theta, unflatten = ravel_pytree(params)

def flat_loss(theta):
    return loss(unflatten(theta))

# Automatic differentiation.
grad_ad = np.asarray(jax.grad(flat_loss)(theta))

# Central finite differences:
# dL/dtheta_i ≈ [L(theta + h*e_i) - L(theta - h*e_i)] / (2*h)
h = 1e-5
grad_fd = np.zeros(theta.size, dtype=np.float64)

for i in range(theta.size):
    step = jnp.zeros_like(theta).at[i].set(h)
    grad_fd[i] = float(
        (flat_loss(theta + step) - flat_loss(theta - step)) / (2 * h)
    )

abs_error = np.abs(grad_ad - grad_fd)
relative_error = abs_error / np.maximum(
    np.maximum(np.abs(grad_ad), np.abs(grad_fd)), 1e-15
)

print("Precision:", theta.dtype)
print(f"Loss: {float(flat_loss(theta)):.10f}")
print("\nParameter       jax.grad       Finite difference    Absolute error")
for i, (ad, fd, err) in enumerate(zip(grad_ad, grad_fd, abs_error)):
    print(f"{i:9d}    {ad: .10f}       {fd: .10f}         {err:.2e}")

print(f"\nMaximum absolute error: {abs_error.max():.3e}")
print(f"Maximum relative error: {relative_error.max():.3e}")

# Relative tolerance of 1e-5 verifies approximately five significant digits.
np.testing.assert_allclose(grad_ad, grad_fd, rtol=1e-5, atol=0.0)
print("PASS: all parameter gradients agree to five significant digits.")

