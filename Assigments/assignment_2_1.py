# Question 11: your code here

import numpy as np

rng = np.random.default_rng(0)
n = 60
repeats = 200
lam = 1e-2

least_squares_results = []
ridge_results = []

for _ in range(repeats):
    x1 = rng.normal(size=n)
    x2 = x1 + 0.02 * rng.normal(size=n)
    y = 3*x1 + 0.3 * rng.normal(size=n)

    X = np.column_stack((x1, x2))

    theta_ls = np.linalg.lstsq(X, y, rcond=None)[0]
    theta_ridge = np.linalg.solve(
        X.T @ X + lam*np.eye(2), X.T @ y
    )

    least_squares_results.append(
        [theta_ls[0], theta_ls[1], theta_ls.sum()]
    )
    ridge_results.append(
        [theta_ridge[0], theta_ridge[1], theta_ridge.sum()]
    )

ls_sd = np.std(least_squares_results, axis=0, ddof=1)
ridge_sd = np.std(ridge_results, axis=0, ddof=1)

print("                    θ₁        θ₂       θ₁+θ₂")
